"""The advance bars on whichever keys pan the display in Braille Settings; never reads the device's own tables."""

import tempfile
import unittest
from pathlib import Path
from types import ModuleType

from panning import ADVANCE, BACK, bar_codes, describe, panning_keys, usable

# What BT Speak's navigation-key-setup writes for Blazie mode, layout by layout (BTSpeak/nav_keys.py)
HEADER = "# Generated by navigation-key-setup -- edit through Braille Settings, not by hand.\n\nbind L1 CHRLT\nbind R1 CHRRT\n"
LAYOUTS = {
    "right-handed": ("bind L2 LNUP\nbind L3 LNDN\nbind R2 FWINLT\nbind R3 FWINRT\n", {"R2": BACK, "R3": ADVANCE}),
    "left-handed": ("bind L2 FWINLT\nbind L3 FWINRT\nbind R2 LNUP\nbind R3 LNDN\n", {"L2": BACK, "L3": ADVANCE}),
    "left-right-nav-and-panning": ("bind L2 LNUP\nbind L3 FWINLT\nbind R2 LNDN\nbind R3 FWINRT\n",
                                   {"L3": BACK, "R3": ADVANCE}),
    "left-right-nav-reverse-panning": ("bind L2 LNUP\nbind L3 FWINRT\nbind R2 LNDN\nbind R3 FWINLT\n",
                                       {"L3": ADVANCE, "R3": BACK}),
}


class PanningTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.user = Path(tmp.name) / "user.kti"
        self.shipped = Path(tmp.name) / "shipped.kti"
        self.shipped.write_text(HEADER + LAYOUTS["right-handed"][0])

    def test_every_layout_pans_on_its_own_keys(self):
        for layout, (table, expected) in LAYOUTS.items():
            with self.subTest(layout=layout):
                self.user.write_text(HEADER + table)
                self.assertEqual(panning_keys((self.user, self.shipped)), expected)

    def test_custom_keys_may_pan_on_both_sides_and_a_combination_is_not_a_bar(self):
        self.user.write_text(HEADER + "bind L2 FWINLT\nbind R2 fwinlt\nbind L3 FWINRT\nbind R3 SAY_LINE\n"
                             "bind L1+R1 FWINRT\nbind Dot7 FWINRT\n# bind R3 FWINRT\n")
        self.assertEqual(panning_keys((self.user, self.shipped)), {"L2": BACK, "R2": BACK, "L3": ADVANCE})

    def test_the_first_table_there_is_the_one_used_even_when_it_pans_nothing(self):
        self.user.write_text(HEADER + "bind L2 LNUP\nbind R2 LNDN\n")
        self.assertEqual(panning_keys((self.user, self.shipped)), {})
        self.user.unlink()
        self.assertEqual(panning_keys((self.user, self.shipped)), {"R2": BACK, "R3": ADVANCE})
        self.shipped.unlink()
        self.assertEqual(panning_keys((self.user, self.shipped)), {"R2": BACK, "R3": ADVANCE})  # an older device

    def test_key_codes_and_help(self):
        kb = ModuleType("kb_client")
        kb.BTB_L3, kb.BTB_R3 = 258, 261  # no BTB_L2: an older library, the key left out rather than failing
        self.assertEqual(bar_codes(kb, {"L3": BACK, "R3": ADVANCE, "L2": ADVANCE}), {258: BACK, 261: ADVANCE})
        self.assertIn("R3 advances braille; L3 moves it back", describe({"L3": BACK, "R3": ADVANCE}))
        self.assertIn("L3 or R3 advances", describe({"L3": ADVANCE, "R3": ADVANCE, "R2": BACK}))
        self.assertIn("No key moves it back", describe({"R3": ADVANCE}))
        self.assertIn("advance bars are unused", describe({}))

    def test_help_names_only_keys_the_keyboard_reports(self):
        legacy = ModuleType("legacy_keyboard")              # the older keypad's bridge: L2, L3, R2, R3 only
        legacy.BTB_L2, legacy.BTB_L3, legacy.BTB_R2, legacy.BTB_R3 = 257, 258, 260, 261
        keys = {"L1": ADVANCE, "R3": ADVANCE, "R2": BACK}
        self.assertEqual(usable(legacy, keys), {"R3": ADVANCE, "R2": BACK})
        self.assertNotIn("L1", describe(usable(legacy, keys)))


if __name__ == "__main__":
    unittest.main()
